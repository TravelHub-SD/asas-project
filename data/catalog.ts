  slug: CitySlug;
  nameAr: string;
  region: string;
  intro: string;
  /** زاوية محلية قصيرة تُستخدم في صفحات المادة داخل المدينة */
  localNote: string;
  regions: Region[];
  /**
   * المواد المعروضة في هذه المدينة. غيابه يعني كل المواد (جدة والرياض).
   * المدن الجديدة تعرض ثلاث مواد فقط، فلا تُبنى لها صفحات لمواد
   * لا تغطيها العميلة فعلًا — وبلا هذا الحقل كانت الروابط الداخلية
   * ستشير إلى صفحات غير مولَّدة فتعطي 404.
   */
  subjectSlugs?: readonly string[];
  /**
   * نصّان خاصّان بالمدينة يحلّان محل الإجابتين العامّتين في الأسئلة الشائعة.
   * بدونهما كانت الإجابتان نفسهما تظهران في المدن السبع كلها، فتزيد تشابه
   * الصفحة مع نظيرتها في مدينة أخرى بقدر ما تزيد تشابهها داخل مدينتها.
   */
