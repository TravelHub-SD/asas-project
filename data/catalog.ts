/** هل المدينة من المدينتين الأساسيتين (لهما زوايا مكتوبة لكل مادة)؟ */
export function isCoreCity(slug: string): slug is CoreCitySlug {
  return slug === "jeddah" || slug === "riyadh";
}

/** الزاوية المحلية للمادة في المدينة، أيًّا كان نوعها. */
export function subjectCityAngle(subject: Subject, city: City): string | undefined {
  if (isCoreCity(city.slug)) return subject.cityAngle[city.slug];
  return subject.expandedCityAngle?.[city.slug];
}

/** النقاط المحلية للمادة — للمدينتين الأساسيتين فقط. */
export function subjectCityFocus(subject: Subject, city: City): string[] {
  if (isCoreCity(city.slug)) return subject.cityFocus[city.slug];
  return subject.expandedCityFocus?.[city.slug] ?? [];
}

/** المواد المعروضة في هذه المدينة، بترتيب SUBJECTS. */
export function citySubjects(city: City): Subject[] {
  if (!city.subjectSlugs) return SUBJECTS;
  const allowed = new Set(city.subjectSlugs);
  return SUBJECTS.filter((s) => allowed.has(s.slug));
}

/** هل تعرض هذه المدينة هذه المادة؟ يمنع الربط إلى صفحة غير مولَّدة. */
export function cityHasSubject(city: City, slug: string): boolean {
  return !city.subjectSlugs || city.subjectSlugs.includes(slug);
}

export function getCity(slug: string): City | undefined {
  return CITIES.find((c) => c.slug === slug);
}

export function getSubject(slug: string): Subject | undefined {
  return SUBJECTS.find((s) => s.slug === slug);
}

export function getRegion(city: City, slug: string): Region | undefined {
  return city.regions.find((r) => r.slug === slug);
}

/** المناطق المنشورة فقط (Phase 1: مناطق جدة). */
export function publishedRegions(city: City): Region[] {
  return city.regions.filter((r) => r.published);
}

/** كل أحياء المدينة المنشورة، والمميّزة (★) أولًا. */
export function allDistricts(city: City): { region: Region; district: District }[] {
  const pairs = publishedRegions(city).flatMap((region) =>
    region.districts.map((district) => ({ region, district }))
  );
  return pairs.sort((a, b) => Number(b.district.featured) - Number(a.district.featured));
}

export function findDistrict(
  city: City,
  slug: string
): { region: Region; district: District } | undefined {
  return allDistricts(city).find((d) => d.district.slug === slug);
}

/** أحياء منطقة واحدة، المميّزة أولًا. */
export function regionDistricts(region: Region): District[] {
  return [...region.districts].sort(
    (a, b) => Number(b.featured) - Number(a.featured)
  );
}

export const PRIORITY_SUBJECTS = SUBJECTS.filter((s) => s.priority);
export const REGULAR_SUBJECTS = SUBJECTS.filter((s) => !s.priority);

/** المواد الأولوية بترتيب PRIORITY_SUBJECT_SLUGS — تُبنى لها صفحات داخل الأحياء المميّزة. */
export function prioritySubjects(): Subject[] {
  return PRIORITY_SUBJECT_SLUGS.map((slug) => getSubject(slug)).filter(
    (s): s is Subject => Boolean(s)
  );
}

export function isPrioritySlug(slug: string): slug is PrioritySubjectSlug {
  return (PRIORITY_SUBJECT_SLUGS as readonly string[]).includes(slug);
}
