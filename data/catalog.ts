export function getCity(slug: string): City | undefined {
  return CITIES.find((c) => c.slug === slug);
}

export function getSubject(slug: string): Subject | undefined {
  return SUBJECTS.find((s) => s.slug === slug);
}

export function getDistrict(
  city: City,
  slug: string
): District | undefined {
  return city.districts.find((d) => d.slug === slug);
}

/** الأحياء المنشورة فقط (Phase 1: جدة). */
export function publishedDistricts(city: City): District[] {
  return city.districts.filter((d) => d.published);
}

export const PRIORITY_SUBJECTS = SUBJECTS.filter((s) => s.priority);
export const REGULAR_SUBJECTS = SUBJECTS.filter((s) => !s.priority);

/** كل التقاطعات مدينة × مادة — تُستخدم في generateStaticParams و sitemap. */
export function citySubjectPairs(): { city: City; subject: Subject }[] {
  return CITIES.flatMap((city) =>
    SUBJECTS.map((subject) => ({ city, subject }))
  );
}
