export type CitySlug = "jeddah" | "riyadh";

export interface District {
  slug: string;
  nameAr: string;
  /** الصيغة المستخدمة داخل الجملة، مثل: "حي الحمدانية" */
  nameArFull: string;
  intro: string;
  nearby: string[];
  /** ثلاث نقاط عن طبيعة الطلب داخل الحي — تمنع تشابه صفحات الأحياء */
  demand: string[];
  /** Phase 1 ينشر أحياء جدة فقط؛ أحياء الرياض تُفتح في Phase 2 بتغيير هذه القيمة. */
  published: boolean;
}

export interface City {
  slug: CitySlug;
  nameAr: string;
  region: string;
  /** فقرة تعريف خاصة بالمدينة تظهر في صفحة المدينة */
  intro: string;
  /** زاوية محلية قصيرة تُستخدم في صفحات المادة داخل المدينة */
  localNote: string;
  districts: District[];
}

export type SubjectKind = "subject" | "program";

export interface Faq {
  q: string;
  a: string;
}

export interface Subject {
  slug: string;
  /** الاسم المعروض في الشبكات والقوائم، مثل: "الإنجليزية" */
  nameAr: string;
  /** الصيغة داخل العنوان H1، مثل: "لغة إنجليزية" */
  h1Noun: string;
  /** بادئة العنوان الكاملة قبل اسم المكان */
  h1Prefix: string;
  /** وصف قصير يظهر في بطاقات الشبكة */
  blurb: string;
  kind: SubjectKind;
  /** المواد المميّزة (التأسيس الدولي والتخاطب) تظهر أولًا */
  priority?: boolean;
  /** المراحل التي تُغطّى */
  stages: string;
  /** فقرة تعريف فريدة لهذه المادة */
  intro: string;
  /** ماذا تفعل المعلمة — مختلفة فعليًا لكل مادة */
  teacherDoes: string[];
  /** النتائج المتوقعة */
  outcomes: string[];
  /** أسئلة شائعة خاصة بالمادة */
  faqs: Faq[];
  /** فقرة إضافية لكل مدينة — تمنع تشابه صفحة جدة مع صفحة الرياض */
  cityAngle: Record<CitySlug, string>;
  /** ثلاث نقاط خاصة بكل مدينة — تمنع تشابه محتوى نفس المادة بين المدن */
  cityFocus: Record<CitySlug, string[]>;
  /** مواد ذات صلة للربط الداخلي */
  related: string[];
}

export interface Curriculum {
  slug: string;
  nameAr: string;
  description: string;
}

export interface Mode {
  slug: string;
  nameAr: string;
  description: string;
}

